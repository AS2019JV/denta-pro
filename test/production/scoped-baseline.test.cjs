test('Scoped verifier catches missing constraints, enum order, ACL escalation and shape changes', () => {
  const { manifest } = fixture(prod, prodDeps, observed);
  const exact = structuredClone(manifest.expectedScopedState);
  assert.equal(verify(manifest, exact).matches, true);
  for (const mutate of [
    s => { s.constraints.pop(); },
    s => { s.types[0].enumLabels.reverse(); },
    s => { s.functions[0].acl = '{postgres=X/postgres,anon=X/postgres}'; },
    s => { s.columns.find(c => c.table === 'services' && c.name === 'price').type = 'numeric'; },
    s => { s.sequences[1].ownedBy = null; },
    s => { s.triggers.pop(); },
    s => { s.relations.find(r => r.kind === 'v').options = null; },
    s => { s.defaultPrivileges[0].acl = '{postgres=X/postgres,anon=X/postgres}'; },
    s => { s.defaultPrivileges = []; },
  ]) { const changed = structuredClone(exact); mutate(changed); assert.equal(verify(manifest, changed).matches, false); }
});
