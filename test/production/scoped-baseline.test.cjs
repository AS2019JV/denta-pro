test('Dropped physical slots compact explicitly; logical reordering and invalid positions still fail', () => {
  const {manifest}=fixture();
  assert.equal(manifest.formatVersion,2);
  assert.ok(manifest.explicitDifferences.some(x=>x.identity==='public.data_rights_requests.resolution_notes' && x.reason.includes('16 compacts to 15')));
  const actual=structuredClone(manifest.expectedScopedState);
  actual.columns.find(c=>c.table==='data_rights_requests' && c.name==='resolution_notes').position=15;
  const comparison=verify(manifest,actual);
  assert.equal(comparison.matches,true);
  assert.deepEqual(comparison.physicalColumnPositionDifferences,[{identity:'public.data_rights_requests.resolution_notes',expectedPhysical:16,actualPhysical:15}]);
  const table=actual.columns.filter(c=>c.table==='patients');
  [table[0].position,table[1].position]=[table[1].position,table[0].position];
  assert.equal(verify(manifest,actual).matches,false);
  table[0].position=table[1].position;
  assert.throws(()=>verify(manifest,actual),/Duplicate column/);
  table[0].position=-1;
  assert.throws(()=>verify(manifest,actual),/Invalid physical/);
});
